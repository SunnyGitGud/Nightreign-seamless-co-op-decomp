#!/usr/bin/env python3
"""Generate src/nrsc/signatures/signature_table.inc from evidence/signatures/signatures.json.

Usage: python3 -I tools/gen_signature_table.py [--check]
  (no flag) rewrite the .inc; --check exits 1 if the checked-in file differs.

Entries are emitted in execution order (see order_key): the builder 0x18006b830 runs first, then
0x1800655a0, then the chunk 0x18006f570 reached by its tail jump (docs/signatures.md section 2).
find1/inline entries carry exec_seq (1..146) which must be strictly increasing in this order.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "evidence", "signatures", "signatures.json")
OUT = os.path.join(ROOT, "src", "nrsc", "signatures", "signature_table.inc")

# Builder code ranges (docs/signatures.md section 2): A = FUN_18006b830, B = FUN_1800655a0, C = FUN_18006f570.
PHASES = [(0x18006B830, 0x18006EE70), (0x1800655A0, 0x180069AF6), (0x18006F570, 0x18007B05B)]
# Execution rank of each range: A first, then B, then C.
PHASE_RANK = [0, 1, 2]

KIND = {"find1": "Find1", "inline": "Inline", "findall": "FindAll", "rtti": "Rtti"}


def order_key(call):
    for (lo, hi), rank in zip(PHASES, PHASE_RANK):
        if lo <= call < hi:
            return (rank, call)
    raise SystemExit("lookup call %#x is outside the builder ranges" % call)


def lit(s):
    # Raw string: no escapes needed, and no trigraph/"??" trouble.
    assert ')sig"' not in s
    return 'R"sig(%s)sig"' % s


def main():
    d = json.load(open(SRC))
    entries = d["entries"]
    rows = []
    for e in entries:
        call = int(e["lookup_call"], 16)
        offs = [int(x, 16) for x in e["table_offsets"]]
        kind = e["kind"]
        text = e["rtti_name"] if kind == "rtti" else e["pattern"]
        if kind == "findall":
            m = re.search(r"signatures\.cpp line (\d+)", e["post_processing"])
            line = int(m.group(1)) if m else 0
        elif kind == "rtti":
            line = 0
        else:
            line = 1000  # failure line of FUN_18007c8f0 and its inlined copies
        rows.append(dict(call=call, kind=kind, offs=offs, text=text, offset=e.get("offset", 0) or 0,
                         mode=e.get("mode") if e.get("mode") is not None else 0,
                         line=line, seq=e.get("exec_seq") or 0))
    rows.sort(key=lambda r: order_key(r["call"]))
    last = 0
    for r in rows:
        if r["seq"]:
            assert r["seq"] > last, "exec_seq not monotonic at %#x" % r["call"]
            last = r["seq"]
    assert last == 146, last
    assert len(rows) == 168

    o = []
    o.append("// GENERATED by tools/gen_signature_table.py from evidence/signatures/signatures.json. DO NOT EDIT.")
    o.append("// Included from signature_table.hpp inside namespace nrsc::signatures.")
    o.append("// One row per lookup of the table builder (FUN_1800655a0 / FUN_18006b830 / FUN_18006f570), in execution order.")
    o.append("// Fields: kind, lookup_call (nrsc.dll VA of the call), exec_order (0-based position), exec_seq (1-based count of")
    o.append("// find1/inline lookups, 0 for find-all and RTTI), table offsets, slot count, offset, mode, fatal line, pattern/name.")
    o.append("inline constexpr SignatureEntry kSignatureEntries[] = {")
    for i, r in enumerate(rows):
        offs = r["offs"]
        assert 1 <= len(offs) <= 4
        offs_txt = ", ".join("0x%x" % x for x in offs + [0] * (4 - len(offs)))
        o.append("    {EntryKind::%s, 0x%xULL, %d, %d, {%s}, %d, %d, %d, %d, %s}," % (
            KIND[r["kind"]], r["call"], i, r["seq"], offs_txt, len(offs), r["offset"], r["mode"], r["line"],
            lit(r["text"])))
    o.append("};")
    o.append("")
    ip = d["installer_patterns"]
    a = [p for p in ip if p.get("lookup_call") == "0x18001f060"][0]
    b = [p for p in ip if p.get("lookup_call") == "0x18001f14b"][0]
    o.append("// Hook installer FUN_18001edb0 (EB patch set). Plain ASCII on the stack there, not XOR-obfuscated.")
    o.append("// A: find-all over the image (call 0x18001f060); B: first match within 0x80 bytes after each A hit (call 0x18001f14b),")
    o.append("// whose byte 0x72 is patched to 0xEB. Owned by the hooks worker; only the pattern text lives here.")
    o.append("inline constexpr std::string_view kInstallerPatternA = %s;" % lit(a["pattern"]))
    o.append("inline constexpr std::string_view kInstallerPatternB = %s;" % lit(b["pattern"]))
    text = "\n".join(o) + "\n"
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        sys.exit(0 if cur == text else 1)
    open(OUT, "w").write(text)
    print("wrote %s (%d entries)" % (OUT, len(rows)))


if __name__ == "__main__":
    main()
